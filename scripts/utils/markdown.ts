function featuredSection(items: MaterialItem[], locale: Locale): string {
  if (items.length === 0) return "";
  let md = `## ⭐ ${t(locale, "featuredTitle", MODEL_NAME)}

> ${t(locale, "featuredSubtitle", MODEL_NAME)}

`;
  items.forEach((m, i) => (md += card(m, i + 1, true, locale)));
  return md;
}

function allPromptsSection(items: MaterialItem[], hidden: number, locale: Locale): string {
  let md = `## 📋 ${t(locale, "allPromptsTitle", MODEL_NAME)}

`;
  items.forEach((m, i) => (md += card(m, FEATURED_COUNT + i + 1, false, locale)));

  if (hidden > 0) {
    md += `<div align="center">

### ➕ ${hidden}+ ${t(locale, "moreInGallery", MODEL_NAME)}

**[→ ${t(locale, "galleryCta", MODEL_NAME)}](${siteUrl("", "cta")})**

</div>

---

`;
  }
  return md;
}

function card(m: MaterialItem, index: number, featured: boolean, locale: Locale): string {
  const width = featured ? 640 : 480;
  const title = cardTitleLocalized(m);
  let md = `### ${index}. ${title}\n\n`;

  md += `![Type](https://img.shields.io/badge/${encodeURIComponent(
    mediaTypeLabel(m.media_type_slug, locale),
  )}-${encodeURIComponent(MODEL_NAME)}-111111)`;
  if (m.is_fallback) {
    md += ` ![fallback](https://img.shields.io/badge/translation-pending-lightgrey)`;
  }
  if (featured && m.tweet?.like_count) {
    md += ` ![Likes](https://img.shields.io/badge/❤️-${encodeURIComponent(
      compact(m.tweet.like_count),
    )}-e0245e)`;
  }
  md += `\n\n`;

  md += mediaBlock(m, width, title, locale);
  md += translationPromptBlock(m, locale);
  md += `📎 [${t(locale, "viewOriginal", MODEL_NAME)}](${originalPromptLink(m.id)})\n\n`;
  md += detailsBlock(m, locale);
  md += `**[▶️ ${t(locale, "watchRemix", MODEL_NAME)}](${siteUrl("", "cta")})**\n\n`;
  md += `---\n\n`;
  return md;
}

function cardTitleLocalized(m: MaterialItem): string {
  if (m.title?.trim()) return oneLine(m.title, 70);
  const readable = primaryReadable(m);
  if (readable) return oneLine(readable, 70);
  return `${MODEL_NAME} Prompt`;
}

function cardTitleSource(m: MaterialItem): string {
  const text = primarySourceText(m);
  return text ? oneLine(text, 70) : `${MODEL_NAME} Prompt`;
}

function primaryReadable(m: MaterialItem): string {
  const p = m.prompt;
  if (p.type === "single") return p.readable || p.text || "";
  return p.video_readable || p.image_readable || p.video || p.image || "";
}

function primarySourceText(m: MaterialItem): string {
  const p = m.prompt;
  if (p.type === "single") return p.text || "";
  return p.video || p.image || "";
}

function mediaBlock(m: MaterialItem, width: number, alt: string, locale: Locale): string {
  const media = m.tweet?.media?.[0];
  const href = siteUrl("", "image");
  if (!media) {
    const ref = m.reference_images?.[0];
    if (!ref) return "";
    return `<div align="center">\n<a href="${href}"><img src="${ref.url}" width="${width}" alt="${escapeAttr(
      alt,
    )}"></a>\n</div>\n\n`;
  }

  const src = media.type === "video" ? media.poster || media.url : media.url;
  let block = `<div align="center">\n<a href="${href}"><img src="${src}" width="${width}" alt="${escapeAttr(
    alt,
  )}"></a>\n`;
  if (media.type === "video") {
    block += `<br><sub>▶️ <a href="${href}">${t(locale, "playOnSite", MODEL_NAME)}</a></sub>\n`;
  }
  block += `</div>\n\n`;
  return block;
}

/** Translation layer — shown in localized READMEs. */
function translationPromptBlock(m: MaterialItem, locale: Locale): string {
  const p = m.prompt;
  if (p.type === "dual") {
    let md = "";
    const img = cleanPrompt(p.image_readable || p.image);
    const vid = cleanPrompt(p.video_readable || p.video);
    if (img) md += `**🖼️ ${t(locale, "imagePromptLabel", MODEL_NAME)}**\n\n\`\`\`\n${img}\n\`\`\`\n\n`;
    if (vid) md += `**🎬 ${t(locale, "videoPromptLabel", MODEL_NAME)}**\n\n\`\`\`\n${vid}\n\`\`\`\n\n`;
    return md;
  }
  const text = cleanPrompt(p.readable || p.text);
  if (!text) return "";
  return `**📝 ${t(locale, "promptLabel", MODEL_NAME)}**\n\n\`\`\`\n${text}\n\`\`\`\n\n`;
}

/** Source layer only — for PROMPTS_ORIGINAL.md. */
function sourcePromptBlock(m: MaterialItem): string {
  const p = m.prompt;
  if (p.type === "dual") {
    let md = "";
    if (p.image) md += `**🖼️ Image prompt (source)**\n\n\`\`\`\n${cleanPrompt(p.image)}\n\`\`\`\n\n`;
    if (p.video) md += `**🎬 Video prompt (source)**\n\n\`\`\`\n${cleanPrompt(p.video)}\n\`\`\`\n\n`;
    return md;
  }
  const text = cleanPrompt(p.text);
  if (!text) return "";
  return `**📝 Prompt (source)**\n\n\`\`\`\n${text}\n\`\`\`\n\n`;
}

function originalCard(m: MaterialItem, index: number): string {
  const title = cardTitleSource(m);
  let md = `<a id="${anchorId(m.id)}"></a>\n\n### ${index}. ${title}\n\n`;
  if (m.source_locale) {
    md += `![${t("en", "sourceLocale", MODEL_NAME)}](https://img.shields.io/badge/${encodeURIComponent(
      m.source_locale,
    )}-source-555555)\n\n`;
  }
  md += sourcePromptBlock(m);
  md += detailsBlock(m, "en");
  md += `---\n\n`;
  return md;
}

function detailsBlock(m: MaterialItem, locale: Locale): string {
  const tw = m.tweet;
  if (!tw) return "";

  const verified = tw.author_verified ? " ✓" : "";
  const followers = tw.author_followers
    ? ` · ${compact(tw.author_followers)} ${t(locale, "followers", MODEL_NAME)}`
    : "";
  const profile = `https://x.com/${tw.author_username}`;

  let md = `**${t(locale, "by", MODEL_NAME)}** [${tw.author_name}${verified}](${profile}) (@${tw.author_username})${followers}\n\n`;

  const metrics: string[] = [];
  if (tw.like_count) metrics.push(`❤️ ${compact(tw.like_count)}`);
  if (tw.retweet_count) metrics.push(`🔁 ${compact(tw.retweet_count)}`);
  if (tw.bookmark_count) metrics.push(`🔖 ${compact(tw.bookmark_count)}`);
  if (tw.view_count) metrics.push(`👁 ${compact(tw.view_count)}`);
  if (metrics.length) md += `${metrics.join(" · ")}\n\n`;

  const date = formatDate(tw.posted_at);
  if (date) md += `<sub>📅 ${date}</sub>\n\n`;
  return md;
}

function contribute(locale: Locale): string {
  const steps = tList(locale, "contributeSteps", MODEL_NAME);
  let md = `## 🤝 ${t(locale, "contributeTitle", MODEL_NAME)}

`;
  steps.forEach((step, i) => {
    const line = step.replace("**new prompt submission**", `[**new prompt submission**](${ISSUE_NEW})`);
    md += `${i + 1}. ${line}\n`;
  });
  md += `\n${t(locale, "contributeSee", MODEL_NAME)}\n\n---\n\n`;
  return md;
}

