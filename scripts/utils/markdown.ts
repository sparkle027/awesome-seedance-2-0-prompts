/**
 * README section renderers.
 *
 * - Localized READMEs: translation layer (readable) + link to PROMPTS_ORIGINAL.md
 * - PROMPTS_ORIGINAL.md: source layer only (text / image / video)
 */
import {
  FEATURED_COUNT,
  GITHUB_REPO,
  MAX_ALL_PROMPTS,
  MODEL_NAME,
  PROMPTS_ORIGINAL_FILE,
  SITE_URL,
  mediaTypeLabel,
  siteUrl,
  type Locale,
} from "./config.js";
import { compact, cleanPrompt, formatDate, oneLine } from "./format.js";
import type { MaterialItem } from "./api-client.js";
import {
  languageNav,
  originalPromptLink,
  t,
  tList,
} from "./i18n.js";

const REPO_URL = `https://github.com/${GITHUB_REPO}`;
const ISSUE_NEW = `${REPO_URL}/issues/new?template=submit-prompt.yml`;

// ---------------------------------------------------------------------------
