// ---------------------------------------------------------------------------

export function generateReadme(items: MaterialItem[], locale: Locale): string {
  const featured = items.slice(0, FEATURED_COUNT);
  const rest = items.slice(FEATURED_COUNT);
  const shown = rest.slice(0, MAX_ALL_PROMPTS - FEATURED_COUNT);
  const hidden = items.length - (featured.length + shown.length);

  return [
    header(items.length, locale),
    galleryCTA(locale),
    toc(locale),
    whatIs(locale),
    apiSection(locale),
    news(locale),
    stats(items.length, locale),
    featuredSection(featured, locale),
    allPromptsSection(shown, hidden, locale),
    contribute(locale),
    footer(locale),
  ].join("");
}

export function generateOriginalPrompts(items: MaterialItem[]): string {
  let md = `# ${messagesOriginalTitle()}\n\n`;
  md += t("en", "originalDocIntro", MODEL_NAME) + "\n\n";
  md += `> ${t("en", "autoGenerated", MODEL_NAME)} · ${SITE_URL.replace(/^https?:\/\//, "")}\n\n`;
  md += `## ${t("en", "originalDocToc", MODEL_NAME)}\n\n`;
  md += items.map((m, i) => `- [${i + 1}. ${cardTitleSource(m)}](#${anchorId(m.id)})`).join("\n");
  md += "\n\n---\n\n";

  items.forEach((m, i) => {
    md += originalCard(m, i + 1);
  });

  md += `\n---\n\n<div align="center">\n\n`;
  md += `[README.md](README.md) · [${t("en", "footerGallery", MODEL_NAME)}](${siteUrl("", "cta")})\n\n</div>\n`;
  return md;
}

function messagesOriginalTitle(): string {
  return t("en", "originalDocTitle", MODEL_NAME);
}

function anchorId(id: string): string {
  return `prompt-${id}`;
}

